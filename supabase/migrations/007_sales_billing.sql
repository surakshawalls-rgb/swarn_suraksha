do $sales_policies$
declare t text;
begin
  foreach t in array array['ss_sales','ss_sale_lines','ss_sale_payments','ss_sale_inventory_movements','ss_sale_cashbook_entries'] loop
    if not exists (select 1 from pg_policies where schemaname='public' and tablename=t and policyname=t || '_read_member') then
      execute format('create policy %I on public.%I for select to authenticated using (public.is_business_member(business_id))',t || '_read_member',t);
    end if;
  end loop;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='ss_sale_audit_events' and policyname='ss_sale_audit_events_read_admin') then
    execute 'create policy ss_sale_audit_events_read_admin on public.ss_sale_audit_events for select to authenticated using (public.has_business_role(business_id, array[''owner'',''admin'']))';
  end if;
end
$sales_policies$;
