-- Atomic sales posting against purchase-owned stock. No tax is inferred here.
-- Requires verified migrations 004-006 and the existing tenant helper functions.
do $preflight$
begin
  if to_regclass('public.customers') is null
     or to_regclass('public.ss_metal_rate_snapshots') is null
     or to_regclass('public.ss_purchases') is null
     or to_regclass('public.ss_purchase_lines') is null
     or to_regclass('public.ss_purchase_payments') is null
     or to_regclass('public.ss_inventory_movements') is null
     or to_regclass('public.ss_cashbook_entries') is null
     or to_regclass('public.ss_audit_events') is null then
    raise exception 'Required verified foundation, rate, purchase, and ledger tables are missing before 007_sales_billing';
  end if;
  if to_regprocedure('public.is_business_member(uuid)') is null
     or to_regprocedure('public.has_business_role(uuid,text[])') is null then
    raise exception 'Tenant authorization functions are missing; inspect hosted RLS before applying 007_sales_billing';
  end if;
  perform public.is_business_member(null::uuid);
  perform public.has_business_role(null::uuid, array[]::text[]);
end
$preflight$;

create unique index if not exists ss_rates_business_id_unique on public.ss_metal_rate_snapshots (business_id,id);

create table if not exists public.ss_sales (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete restrict,
  customer_id uuid,
  invoice_number bigint generated by default as identity,
  idempotency_key uuid not null,
  request_payload jsonb not null,
  subtotal numeric(14,2) not null check (subtotal > 0),
  paid_total numeric(14,2) not null check (paid_total >= 0 and paid_total <= subtotal),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  unique (business_id,id),
  unique (business_id,idempotency_key),
  unique (business_id,invoice_number),
  foreign key (business_id,customer_id) references public.customers(business_id,id) on delete restrict
);

create table if not exists public.ss_sale_lines (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  sale_id uuid not null,
  line_number smallint not null check (line_number between 1 and 100),
  item_description text not null check (length(trim(item_description)) between 1 and 180),
  metal text not null check (metal in ('gold','silver','other')),
  purity text,
  gross_weight_g numeric(14,4) not null check (gross_weight_g > 0),
  net_weight_g numeric(14,4) not null check (net_weight_g > 0 and net_weight_g <= gross_weight_g),
  rate_snapshot_id uuid not null,
  unit_rate_per_gram numeric(14,4) not null check (unit_rate_per_gram > 0),
  making_charge numeric(14,2) not null default 0 check (making_charge >= 0),
  line_total numeric(14,2) not null check (line_total > 0),
  created_at timestamptz not null default now(),
  check (purity is null or length(trim(purity)) <= 40),
  unique (sale_id,line_number),
  foreign key (business_id,sale_id) references public.ss_sales(business_id,id) on delete restrict,
  foreign key (business_id,rate_snapshot_id) references public.ss_metal_rate_snapshots(business_id,id) on delete restrict
);

create table if not exists public.ss_sale_payments (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  sale_id uuid not null,
  method text not null check (method in ('cash','upi','bank_transfer','card')),
  amount numeric(14,2) not null check (amount > 0),
  reference text check (reference is null or length(reference) <= 120),
  received_by uuid not null references auth.users(id),
  recorded_at timestamptz not null default now(),
  foreign key (business_id,sale_id) references public.ss_sales(business_id,id) on delete restrict
);

-- Separate append-only ledgers preserve migration 006's existing purchase-only shapes.
