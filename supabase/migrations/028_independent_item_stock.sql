create or replace function public.ss_stock_summary(p_business_id uuid)
returns table(metal text,available_weight_g numeric,available_items bigint)
language plpgsql stable security definer set search_path=''
as $function$
begin
  if not public.is_business_member(p_business_id) then
    raise exception 'Not authorized to read stock for this business' using errcode='42501';
  end if;
  return query
    select i.metal,sum(i.weight_g),count(*)
    from public.ss_stock_items i
    where i.business_id=p_business_id and i.status='available'
    group by i.metal
    order by i.metal;
end
$function$;
revoke all on function public.ss_stock_summary(uuid) from public,anon;
grant execute on function public.ss_stock_summary(uuid) to authenticated;

create or replace function public.ss_stock_intake(
  p_business_id uuid,p_supplier_id uuid,p_idempotency_key uuid,p_received_date date,
  p_items jsonb,p_initial_paid numeric default 0,p_payment_method text default null,
  p_payment_date date default null,p_payment_reference text default null
) returns uuid
language plpgsql security definer set search_path=''
as $function$
declare
  actor uuid := (select auth.uid());
  payload jsonb;
  old_payload jsonb;
  intake_id uuid;
  item jsonb;
  item_no integer:=0;
  total numeric(14,2):=0;
  item_weight numeric(14,4);
  item_cost numeric(14,2);
  paid numeric(14,2):=coalesce(p_initial_paid,0);
  payment_id uuid;
begin
  if actor is null then raise exception 'Authentication required' using errcode='42501'; end if;
  if p_business_id is null or not public.has_business_role(p_business_id,array['owner','admin']) then
    raise exception 'Not authorized to record stock for this business' using errcode='42501';
  end if;
  if p_idempotency_key is null or p_received_date is null or p_received_date>(now() at time zone 'Asia/Kolkata')::date
     or jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) not between 1 and 100
     or paid<0 or paid*100<>trunc(paid*100)
     or (p_payment_method is not null and p_payment_method not in ('cash','upi','bank_transfer','card'))
     or (p_payment_reference is not null and length(p_payment_reference)>120) then
    raise exception 'Stock intake date, items, or initial payment are invalid' using errcode='22023';
  end if;
  if paid>0 and (p_payment_method is null or p_payment_date is null or p_payment_date<p_received_date or p_payment_date>(now() at time zone 'Asia/Kolkata')::date) then
    raise exception 'A valid payment method and date are required for an initial payment' using errcode='22023';
  end if;
  if paid=0 and (p_payment_method is not null or p_payment_date is not null or p_payment_reference is not null) then
    raise exception 'Payment details must be empty when no initial payment is recorded' using errcode='22023';
  end if;
  payload:=jsonb_build_object('supplier_id',p_supplier_id,'received_date',p_received_date,'items',p_items,
    'initial_paid',paid,'payment_method',p_payment_method,'payment_date',p_payment_date,'payment_reference',p_payment_reference);
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_business_id::text||':'||p_idempotency_key::text,0));
  select id,request_payload into intake_id,old_payload from public.ss_stock_intakes
    where business_id=p_business_id and idempotency_key=p_idempotency_key;
  if intake_id is not null then
    if old_payload<>payload then raise exception 'Idempotency key was already used for a different stock intake' using errcode='22023'; end if;
    return intake_id;
  end if;
  perform 1 from public.ss_suppliers where business_id=p_business_id and id=p_supplier_id and is_active for share;
  if not found then raise exception 'Choose an active manufacturer/supplier in this business' using errcode='23503'; end if;
  for item in select value from jsonb_array_elements(p_items) loop
    item_no:=item_no+1;
    item_weight:=(item->>'weight_g')::numeric;
    item_cost:=(item->>'purchase_cost')::numeric;
    if nullif(trim(item->>'description'),'') is null or length(trim(item->>'description'))>180
       or item->>'metal' not in ('gold','silver') or item_weight<=0 or item_weight*10000<>trunc(item_weight*10000)
       or item_cost<=0 or item_cost*100<>trunc(item_cost*100)
       or length(coalesce(item->>'purity',''))>40 then
      raise exception 'Stock item % has an invalid name, metal, weight, purity, or purchase price',item_no using errcode='22023';
    end if;
    total:=total+item_cost;
  end loop;
  if paid>total then raise exception 'Initial payment cannot exceed total purchase cost' using errcode='22023'; end if;
  insert into public.ss_stock_intakes(business_id,supplier_id,idempotency_key,request_payload,received_date,item_count,total_cost,paid_total,created_by)
    values(p_business_id,p_supplier_id,p_idempotency_key,payload,p_received_date,item_no,total,paid,actor) returning id into intake_id;
  item_no:=0;
  for item in select value from jsonb_array_elements(p_items) loop
    item_no:=item_no+1;
    insert into public.ss_stock_items(business_id,intake_id,item_number,description,metal,purity,weight_g,purchase_cost)
      values(p_business_id,intake_id,item_no,trim(item->>'description'),item->>'metal',nullif(trim(item->>'purity'),''),(item->>'weight_g')::numeric,(item->>'purchase_cost')::numeric);
  end loop;
  if paid>0 then
    insert into public.ss_stock_payments(business_id,intake_id,idempotency_key,request_payload,amount,method,reference,payment_date,created_by)
      values(p_business_id,intake_id,p_idempotency_key,payload,paid,p_payment_method,nullif(trim(p_payment_reference),''),p_payment_date,actor)
      returning id into payment_id;
  end if;
  return intake_id;
end
$function$;
revoke all on function public.ss_stock_intake(uuid,uuid,uuid,date,jsonb,numeric,text,date,text) from public,anon,authenticated;
grant execute on function public.ss_stock_intake(uuid,uuid,uuid,date,jsonb,numeric,text,date,text) to authenticated;

create or replace function public.ss_stock_record_payment(
  p_business_id uuid,p_intake_id uuid,p_idempotency_key uuid,p_amount numeric,p_method text,
  p_payment_date date,p_reference text default null
) returns uuid
language plpgsql security definer set search_path=''
as $function$
declare
  actor uuid := (select auth.uid());
  intake public.ss_stock_intakes%rowtype;
  old public.ss_stock_payments%rowtype;
  payload jsonb;
  payment_id uuid;
begin
  if actor is null then raise exception 'Authentication required' using errcode='42501'; end if;
  if p_business_id is null or not public.has_business_role(p_business_id,array['owner','admin']) then
    raise exception 'Not authorized to settle stock purchase payments' using errcode='42501';
  end if;
  if p_idempotency_key is null or p_amount is null or p_amount<=0 or p_amount*100<>trunc(p_amount*100)
     or p_method is null or p_method not in ('cash','upi','bank_transfer','card') or p_payment_date is null
     or p_payment_date>(now() at time zone 'Asia/Kolkata')::date
     or length(coalesce(p_reference,''))>120 then
    raise exception 'Payment amount, method, date, or reference is invalid' using errcode='22023';
  end if;
  payload:=jsonb_build_object('intake_id',p_intake_id,'amount',p_amount,'method',p_method,'payment_date',p_payment_date,'reference',p_reference);
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_business_id::text||':'||p_idempotency_key::text,0));
  select * into old from public.ss_stock_payments where business_id=p_business_id and idempotency_key=p_idempotency_key;
  if found then
    if old.request_payload<>payload then raise exception 'Idempotency key was already used for a different stock payment' using errcode='22023'; end if;
    return old.id;
  end if;
  select * into intake from public.ss_stock_intakes where business_id=p_business_id and id=p_intake_id for update;
  if not found then raise exception 'Stock intake not found' using errcode='P0002'; end if;
  if p_payment_date<intake.received_date then raise exception 'Payment date cannot be before the stock intake date' using errcode='22023'; end if;
  if p_amount>intake.total_cost-intake.paid_total then raise exception 'Payment exceeds the remaining manufacturer balance' using errcode='22023'; end if;
  insert into public.ss_stock_payments(business_id,intake_id,idempotency_key,request_payload,amount,method,reference,payment_date,created_by)
    values(p_business_id,p_intake_id,p_idempotency_key,payload,p_amount,p_method,nullif(trim(p_reference),''),p_payment_date,actor)
    returning id into payment_id;
  update public.ss_stock_intakes set paid_total=paid_total+p_amount where id=p_intake_id and business_id=p_business_id;
  return payment_id;
end
$function$;
revoke all on function public.ss_stock_record_payment(uuid,uuid,uuid,numeric,text,date,text) from public,anon,authenticated;
grant execute on function public.ss_stock_record_payment(uuid,uuid,uuid,numeric,text,date,text) to authenticated;

create or replace function public.ss_stock_mark_sold(
  p_business_id uuid,p_stock_item_id uuid,p_idempotency_key uuid,p_sold_to text,p_sold_date date
) returns uuid
language plpgsql security definer set search_path=''
as $function$
declare
  actor uuid := (select auth.uid());
  old public.ss_stock_item_events%rowtype;
  event_id uuid;
  payload jsonb;
  received_date date;
begin
  if actor is null then raise exception 'Authentication required' using errcode='42501'; end if;
  if p_business_id is null or not public.has_business_role(p_business_id,array['owner','admin'])
     or p_idempotency_key is null or length(trim(coalesce(p_sold_to,''))) not between 1 and 160
     or p_sold_date is null or p_sold_date>(now() at time zone 'Asia/Kolkata')::date then
    raise exception 'Sale details or stock permissions are invalid' using errcode='22023';
  end if;
  payload:=jsonb_build_object('stock_item_id',p_stock_item_id,'sold_to',trim(p_sold_to),'sold_date',p_sold_date);
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_business_id::text||':'||p_idempotency_key::text,0));
  select * into old from public.ss_stock_item_events where business_id=p_business_id and idempotency_key=p_idempotency_key;
  if found then
    if old.event_type<>'sold' or old.stock_item_id<>p_stock_item_id or old.request_payload<>payload then
      raise exception 'Idempotency key was already used for a different stock action' using errcode='22023';
    end if;
    return old.id;
  end if;
  select intake.received_date into received_date
    from public.ss_stock_items item
    join public.ss_stock_intakes intake on intake.business_id=item.business_id and intake.id=item.intake_id
    where item.business_id=p_business_id and item.id=p_stock_item_id and item.status='available'
    for update of item;
  if not found then raise exception 'Only an available stock item can be marked sold' using errcode='22023'; end if;
  if p_sold_date<received_date then raise exception 'Sale date cannot be before the stock intake date' using errcode='22023'; end if;
  update public.ss_stock_items set status='sold',sold_to=trim(p_sold_to),sold_date=p_sold_date
    where business_id=p_business_id and id=p_stock_item_id and status='available';
  if not found then raise exception 'Only an available stock item can be marked sold' using errcode='22023'; end if;
  insert into public.ss_stock_item_events(business_id,stock_item_id,idempotency_key,event_type,request_payload,actor_user_id)
    values(p_business_id,p_stock_item_id,p_idempotency_key,'sold',payload,actor) returning id into event_id;
  return event_id;
end
$function$;
revoke all on function public.ss_stock_mark_sold(uuid,uuid,uuid,text,date) from public,anon,authenticated;
grant execute on function public.ss_stock_mark_sold(uuid,uuid,uuid,text,date) to authenticated;

