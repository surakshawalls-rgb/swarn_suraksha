create table public.ss_stock_intakes (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete restrict,
  supplier_id uuid not null,
  intake_number bigint generated by default as identity,
  idempotency_key uuid not null,
  request_payload jsonb not null,
  received_date date not null,
  item_count smallint not null check (item_count between 1 and 100),
  total_cost numeric(14,2) not null check (total_cost > 0),
  paid_total numeric(14,2) not null default 0 check (paid_total >= 0 and paid_total <= total_cost),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  unique (business_id,id),
  unique (business_id,idempotency_key),
  unique (business_id,intake_number),
  foreign key (business_id,supplier_id) references public.ss_suppliers(business_id,id) on delete restrict
);

create table public.ss_stock_items (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  intake_id uuid not null,
  item_number smallint not null check (item_number between 1 and 100),
  description text not null check (length(trim(description)) between 1 and 180),
  metal text not null check (metal in ('gold','silver')),
  purity text check (purity is null or length(trim(purity)) between 1 and 40),
  weight_g numeric(14,4) not null check (weight_g > 0),
  purchase_cost numeric(14,2) not null check (purchase_cost > 0),
  status text not null default 'available' check (status in ('available','sold','returned')),
  sold_to text check (sold_to is null or length(trim(sold_to)) between 1 and 160),
  sold_date date,
  return_reason text check (return_reason in ('defect','customer_disliked','different_design','other')),
  return_note text check (return_note is null or length(trim(return_note)) <= 500),
  returned_date date,
  created_at timestamptz not null default now(),
  unique (intake_id,item_number),
  unique (business_id,id),
  foreign key (business_id,intake_id) references public.ss_stock_intakes(business_id,id) on delete restrict,
  check (
    (status='available' and sold_to is null and sold_date is null and return_reason is null and returned_date is null)
    or (status='sold' and sold_to is not null and sold_date is not null and return_reason is null and returned_date is null)
    or (status='returned' and sold_to is null and sold_date is null and return_reason is not null and returned_date is not null)
  )
);

