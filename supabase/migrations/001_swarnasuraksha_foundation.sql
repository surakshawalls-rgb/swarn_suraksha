create extension if not exists pgcrypto;

create table if not exists public.user_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  mobile_number text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.business_profiles (
  id uuid primary key default gen_random_uuid(),
  business_name text not null check (length(trim(business_name)) between 2 and 160),
  owner_contact_name text,
  mobile_number text,
  address text,
  city text,
  state text,
  postal_code text,
  currency_code text not null default 'INR' check (currency_code = 'INR'),
  timezone text not null default 'Asia/Kolkata',
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.business_members (
  business_id uuid not null references public.business_profiles(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner','admin','staff')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  primary key (business_id, user_id)
);

create table if not exists public.business_settings (
  business_id uuid primary key references public.business_profiles(id) on delete cascade,
  gold_rate_policy jsonb not null default '{}'::jsonb,
  silver_rate_policy jsonb not null default '{}'::jsonb,
  payment_methods text[] not null default array['cash','upi','bank_transfer','card'],
  tax_configuration jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete cascade,
  customer_number bigint generated by default as identity,
  name text not null check (length(trim(name)) between 1 and 160),
  mobile_number text,
  email text,
  address text,
  notes text,
  is_active boolean not null default true,
  created_by uuid not null default auth.uid() references auth.users(id),
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (business_id, id)
);
create index if not exists customers_business_name_idx on public.customers (business_id, lower(name));
create index if not exists customers_business_mobile_idx on public.customers (business_id, mobile_number);

create table if not exists public.metal_rate_snapshots (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete cascade,
  metal text not null check (metal in ('gold','silver')),
  purity text,
  rate_per_gram numeric(14,4) not null check (rate_per_gram > 0),
  source text not null,
  fetched_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists metal_rates_latest_idx on public.metal_rate_snapshots (business_id, metal, fetched_at desc);

create table if not exists public.audit_logs (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete cascade,
  actor_user_id uuid references auth.users(id),
  action text not null,
  entity_type text not null,
  entity_id uuid,
  safe_metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.is_business_member(target_business_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.business_members m
    where m.business_id = target_business_id and m.user_id = (select auth.uid()) and m.is_active
  );
$$;
revoke all on function public.is_business_member(uuid) from public;
grant execute on function public.is_business_member(uuid) to authenticated;

create or replace function public.has_business_role(target_business_id uuid, allowed_roles text[])
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.business_members m
    where m.business_id = target_business_id and m.user_id = (select auth.uid())
      and m.is_active and m.role = any(allowed_roles)
  );
$$;
revoke all on function public.has_business_role(uuid,text[]) from public;
grant execute on function public.has_business_role(uuid,text[]) to authenticated;

create or replace function public.create_business(
  p_business_name text, p_owner_contact_name text default null, p_mobile_number text default null,
  p_address text default null, p_city text default null, p_state text default null, p_postal_code text default null
) returns uuid language plpgsql security definer set search_path = '' as $$
declare new_business_id uuid;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  insert into public.business_profiles (business_name, owner_contact_name, mobile_number, address, city, state, postal_code, created_by)
  values (trim(p_business_name), p_owner_contact_name, p_mobile_number, p_address, p_city, p_state, p_postal_code, auth.uid())
  returning id into new_business_id;
  insert into public.business_members (business_id, user_id, role) values (new_business_id, auth.uid(), 'owner');
  insert into public.business_settings (business_id) values (new_business_id);
  return new_business_id;
end;
$$;
revoke all on function public.create_business(text,text,text,text,text,text,text) from public;
grant execute on function public.create_business(text,text,text,text,text,text,text) to authenticated;

