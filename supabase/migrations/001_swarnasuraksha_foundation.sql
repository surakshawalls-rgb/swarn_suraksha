create policy profile_read_self on public.user_profiles for select to authenticated using (user_id = (select auth.uid()));
create policy profile_insert_self on public.user_profiles for insert to authenticated with check (user_id = (select auth.uid()));
create policy profile_update_self on public.user_profiles for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

create policy business_read_member on public.business_profiles for select to authenticated using (public.is_business_member(id));
create policy business_update_owner_admin on public.business_profiles for update to authenticated using (
  public.has_business_role(id, array['owner','admin'])
) with check (public.is_business_member(id));

create policy members_read_self_or_admin on public.business_members for select to authenticated using (
  user_id = (select auth.uid()) or public.has_business_role(public.business_members.business_id, array['owner','admin'])
);
-- Membership writes are intentionally withheld from direct clients; add audited admin RPCs before member management.

create policy settings_read_member on public.business_settings for select to authenticated using (public.is_business_member(business_id));
create policy settings_update_admin on public.business_settings for update to authenticated using (
  public.has_business_role(public.business_settings.business_id, array['owner','admin'])
) with check (public.is_business_member(business_id));

create policy customers_read_member on public.customers for select to authenticated using (public.is_business_member(business_id));
create policy customers_insert_member on public.customers for insert to authenticated with check (public.is_business_member(business_id) and created_by = (select auth.uid()));
create policy customers_update_member on public.customers for update to authenticated using (public.is_business_member(business_id)) with check (public.is_business_member(business_id));

create policy rates_read_member on public.metal_rate_snapshots for select to authenticated using (public.is_business_member(business_id));
create policy rates_insert_admin on public.metal_rate_snapshots for insert to authenticated with check (
  public.has_business_role(public.metal_rate_snapshots.business_id, array['owner','admin'])
);
create policy audit_read_admin on public.audit_logs for select to authenticated using (
  public.has_business_role(public.audit_logs.business_id, array['owner','admin'])
);
-- No client insert/update/delete policies on audit logs: trusted database functions own audit writes.
