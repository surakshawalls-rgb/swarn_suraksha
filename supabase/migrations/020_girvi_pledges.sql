create or replace function public.ss_girvi_completed_months(p_start date,p_as_of date)
returns integer language plpgsql immutable set search_path=''
as $function$
declare months integer;
begin
  months := greatest(0,(extract(year from p_as_of)::integer-extract(year from p_start)::integer)*12
    + extract(month from p_as_of)::integer-extract(month from p_start)::integer);
  if (p_start + make_interval(months=>months))::date > p_as_of then months := months-1; end if;
  return greatest(0,months);
end
$function$;
revoke all on function public.ss_girvi_completed_months(date,date) from public,anon,authenticated;

create or replace function public.ss_girvi_create(
  p_business_id uuid,p_customer_id uuid,p_idempotency_key uuid,p_metal text,p_purity text,
  p_weight_g numeric,p_rate_per_gram numeric,p_principal numeric,p_monthly_interest_percent numeric,
  p_girvi_date date,p_notes text default null
) returns uuid language plpgsql security definer set search_path=''
as $function$
declare actor uuid:=(select auth.uid()); new_id uuid; market_value numeric(14,2); existing uuid; old_payload jsonb; payload jsonb;
begin
  if actor is null then raise exception 'Authentication required' using errcode='42501'; end if;
  if not public.has_business_role(p_business_id,array['owner','admin']) then raise exception 'Not authorized for this business' using errcode='42501'; end if;
  if p_idempotency_key is null or p_metal not in ('gold','silver') or
     (p_metal='gold' and p_purity not in ('24K','22K','20K','18K')) or
     (p_metal='silver' and p_purity is not null) or p_weight_g is null or p_weight_g<=0 or p_weight_g*10000<>trunc(p_weight_g*10000) or
     p_rate_per_gram is null or p_rate_per_gram<=0 or p_rate_per_gram*10000<>trunc(p_rate_per_gram*10000) or
     p_principal is null or p_principal<=0 or p_principal*100<>trunc(p_principal*100) or
     p_monthly_interest_percent is null or p_monthly_interest_percent not between 2 and 6 or
     p_monthly_interest_percent*100<>trunc(p_monthly_interest_percent*100) or p_girvi_date is null or p_girvi_date>current_date or
     length(coalesce(p_notes,''))>2000 then
    raise exception 'Girvi details are invalid' using errcode='22023';
  end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_business_id::text||':'||p_idempotency_key::text,0));
  payload:=jsonb_build_object('customer_id',p_customer_id,'metal',p_metal,'purity',p_purity,'weight_g',p_weight_g,
    'rate_per_gram',p_rate_per_gram,'principal',p_principal,'monthly_interest_percent',p_monthly_interest_percent,
    'girvi_date',p_girvi_date,'notes',nullif(trim(p_notes),''));
  select id,request_payload into existing,old_payload from public.ss_girvi where business_id=p_business_id and idempotency_key=p_idempotency_key;
  if existing is not null then
    if old_payload<>payload then raise exception 'Idempotency key was already used for a different Girvi record' using errcode='22023'; end if;
    return existing;
  end if;
  perform 1 from public.customers where business_id=p_business_id and id=p_customer_id for share;
  if not found then raise exception 'Customer does not belong to this business' using errcode='23503'; end if;
  market_value:=round(p_weight_g*p_rate_per_gram,2);
  if market_value<=0 then raise exception 'Estimated market value is invalid' using errcode='22003'; end if;
  insert into public.ss_girvi(business_id,customer_id,idempotency_key,request_payload,metal,purity,weight_g,rate_per_gram,
    estimated_market_value,principal_amount,principal_balance,monthly_interest_percent,girvi_date,notes,created_by)
  values(p_business_id,p_customer_id,p_idempotency_key,payload,p_metal,p_purity,p_weight_g,p_rate_per_gram,
    market_value,p_principal,p_principal,p_monthly_interest_percent,p_girvi_date,nullif(trim(p_notes),''),actor)
  returning id into new_id;
  insert into public.ss_girvi_audit_events(business_id,girvi_id,actor_user_id,event_type,safe_metadata)
    values(p_business_id,new_id,actor,'girvi.created',jsonb_build_object('principal',p_principal,'estimated_market_value',market_value));
  return new_id;
end
$function$;

create or replace function public.ss_girvi_record_payment(
  p_business_id uuid,p_girvi_id uuid,p_idempotency_key uuid,p_amount numeric,p_method text,p_payment_date date default current_date
) returns jsonb language plpgsql security definer set search_path=''
as $function$
declare actor uuid:=(select auth.uid()); pledge public.ss_girvi%rowtype; prior public.ss_girvi_payments%rowtype;
  months integer; i integer; interest_due numeric(14,2); principal_paid numeric(14,2);
  interest_paid numeric(14,2); total_due numeric(14,2); payment_id uuid;
begin
  if actor is null then raise exception 'Authentication required' using errcode='42501'; end if;
  select * into pledge from public.ss_girvi where business_id=p_business_id and id=p_girvi_id for update;
  if not found or not public.has_business_role(p_business_id,array['owner','admin']) then raise exception 'Girvi record is missing or payment is not authorized' using errcode='42501'; end if;
  if p_idempotency_key is null or p_amount is null or p_amount<=0 or p_amount*100<>trunc(p_amount*100) or
     p_method not in ('cash','upi','bank_transfer','card') or p_payment_date is null or
     p_payment_date>current_date or p_payment_date<pledge.girvi_date then
    raise exception 'Payment amount, method, date or idempotency key is invalid' using errcode='22023';
  end if;
  select * into prior from public.ss_girvi_payments where business_id=p_business_id and idempotency_key=p_idempotency_key;
  if found then
    if prior.girvi_id<>p_girvi_id or prior.amount<>p_amount or prior.payment_method<>p_method or prior.payment_date<>p_payment_date then
      raise exception 'Idempotency key was already used for a different payment' using errcode='22023';
    end if;
    return jsonb_build_object('payment_id',prior.id,'status',pledge.status);
  end if;
  if pledge.status<>'active' then raise exception 'Closed Girvi records cannot receive payments' using errcode='22023'; end if;
  months:=public.ss_girvi_completed_months(pledge.girvi_date,p_payment_date);
  if months<pledge.last_accrued_months then raise exception 'Payment date cannot precede a previously accrued month' using errcode='22023'; end if;
  for i in pledge.last_accrued_months+1..months loop
    pledge.interest_balance:=pledge.interest_balance+round((pledge.principal_balance+pledge.interest_balance)*pledge.monthly_interest_percent/100,2);
  end loop;
  total_due:=pledge.principal_balance+pledge.interest_balance;
  if p_amount>total_due then raise exception 'Payment exceeds the current Girvi outstanding' using errcode='22023'; end if;
  interest_due:=pledge.interest_balance;
  interest_paid:=least(p_amount,interest_due);
  principal_paid:=p_amount-interest_paid;
  pledge.interest_balance:=pledge.interest_balance-interest_paid;
  pledge.principal_balance:=pledge.principal_balance-principal_paid;
  insert into public.ss_girvi_payments(business_id,girvi_id,idempotency_key,amount,payment_method,interest_paid,principal_paid,payment_date,received_by)
    values(p_business_id,p_girvi_id,p_idempotency_key,p_amount,p_method,interest_paid,principal_paid,p_payment_date,actor)
    returning id into payment_id;
  if pledge.principal_balance=0 and pledge.interest_balance=0 then
    update public.ss_girvi set principal_balance=0,interest_balance=0,last_accrued_months=months,
      status='closed',closed_at=now(),jewellery_returned=true,returned_at=now(),updated_at=now() where id=p_girvi_id;
    insert into public.ss_girvi_audit_events(business_id,girvi_id,actor_user_id,event_type,payment_id,safe_metadata)
      values(p_business_id,p_girvi_id,actor,'girvi.closed',payment_id,jsonb_build_object('payment',p_amount));
  else
    update public.ss_girvi set principal_balance=pledge.principal_balance,interest_balance=pledge.interest_balance,
      last_accrued_months=months,updated_at=now() where id=p_girvi_id;
    insert into public.ss_girvi_audit_events(business_id,girvi_id,actor_user_id,event_type,payment_id,safe_metadata)
      values(p_business_id,p_girvi_id,actor,'girvi.payment',payment_id,jsonb_build_object('payment',p_amount,'interest_paid',interest_paid,'principal_paid',principal_paid));
  end if;
  return jsonb_build_object('payment_id',payment_id,'interest_paid',interest_paid,'principal_paid',principal_paid,
    'principal_balance',pledge.principal_balance,'interest_balance',pledge.interest_balance,
    'status',case when pledge.principal_balance=0 and pledge.interest_balance=0 then 'closed' else 'active' end);
end
$function$;

