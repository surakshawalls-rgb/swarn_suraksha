do $preflight$
begin
  if to_regclass('public.customers') is null
     or to_regclass('public.business_profiles') is null
     or to_regprocedure('public.has_business_role(uuid,text[])') is null then
    raise exception 'Verified customers, business profiles and tenant role helper are required before 020_girvi_pledges';
  end if;
  perform public.has_business_role(null::uuid, array[]::text[]);
end
$preflight$;

create table public.ss_girvi (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete restrict,
  customer_id uuid not null,
  girvi_number bigint generated by default as identity,
  idempotency_key uuid not null,
  request_payload jsonb not null,
  metal text not null check (metal in ('gold','silver')),
  purity text,
  weight_g numeric(14,4) not null check (weight_g > 0),
  rate_per_gram numeric(14,4) not null check (rate_per_gram > 0),
  estimated_market_value numeric(14,2) not null check (estimated_market_value > 0),
  principal_amount numeric(14,2) not null check (principal_amount > 0),
  principal_balance numeric(14,2) not null check (principal_balance >= 0),
  interest_balance numeric(14,2) not null default 0 check (interest_balance >= 0),
  monthly_interest_percent numeric(5,2) not null check (monthly_interest_percent between 2 and 6),
  girvi_date date not null,
  last_accrued_months integer not null default 0 check (last_accrued_months >= 0),
  status text not null default 'active' check (status in ('active','closed')),
  closed_at timestamptz,
  jewellery_returned boolean not null default false,
  returned_at timestamptz,
  notes text,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (business_id,id),
  unique (business_id,girvi_number),
  unique (business_id,idempotency_key),
  foreign key (business_id,customer_id) references public.customers(business_id,id) on delete restrict,
  check ((metal='gold' and purity in ('24K','22K','20K','18K')) or (metal='silver' and purity is null)),
  check ((status='closed' and closed_at is not null and jewellery_returned and returned_at is not null)
      or (status='active' and closed_at is null and not jewellery_returned and returned_at is null))
);

create table public.ss_girvi_payments (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  girvi_id uuid not null,
  idempotency_key uuid not null,
  amount numeric(14,2) not null check (amount > 0),
  payment_method text not null check (payment_method in ('cash','upi','bank_transfer','card')),
  interest_paid numeric(14,2) not null check (interest_paid >= 0),
  principal_paid numeric(14,2) not null check (principal_paid >= 0),
  payment_date date not null,
  received_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  unique (business_id,idempotency_key),
  foreign key (business_id,girvi_id) references public.ss_girvi(business_id,id) on delete restrict,
  check (amount=interest_paid+principal_paid)
);

create table public.ss_girvi_audit_events (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  girvi_id uuid not null,
  actor_user_id uuid not null references auth.users(id),
  event_type text not null check (event_type in ('girvi.created','girvi.payment','girvi.closed')),
  payment_id uuid,
  safe_metadata jsonb not null default '{}'::jsonb,
  recorded_at timestamptz not null default now(),
  foreign key (business_id,girvi_id) references public.ss_girvi(business_id,id) on delete restrict,
  foreign key (payment_id) references public.ss_girvi_payments(id) on delete restrict
);

create index ss_girvi_business_date_idx on public.ss_girvi(business_id,created_at desc);
