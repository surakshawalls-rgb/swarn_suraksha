create or replace function public.ss_post_purchase(
  p_business_id uuid,
  p_supplier_id uuid,
  p_idempotency_key uuid,
  p_lines jsonb,
  p_payments jsonb
) returns uuid
language plpgsql
security definer
set search_path = ''
as $function$
declare
  actor uuid := (select auth.uid());
  payload jsonb;
  old_payload jsonb;
  purchase_id uuid;
  computed_subtotal numeric(14,2) := 0;
  computed_paid numeric(14,2) := 0;
  computed_line numeric(14,2);
  line jsonb;
  payment jsonb;
  line_no integer := 0;
  payment_method text;
  payment_amount numeric;
  gross_weight numeric;
  net_weight numeric;
  unit_cost numeric;
  additional_cost numeric;
  purchase_line_id uuid;
  payment_id uuid;
  supplier_active boolean;
begin
  if actor is null then raise exception 'Authentication required' using errcode='42501'; end if;
  if not public.has_business_role(p_business_id, array['owner','admin']) then
    raise exception 'Not authorized for this business' using errcode='42501';
  end if;
  if jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) not between 1 and 100 then
    raise exception 'Purchase requires between 1 and 100 item lines' using errcode='22023';
  end if;
  if jsonb_typeof(p_payments) <> 'array' or jsonb_array_length(p_payments) > 20 then
    raise exception 'Payments must be an array with at most 20 entries' using errcode='22023';
  end if;
  payload := jsonb_build_object('supplier_id', p_supplier_id, 'lines', p_lines, 'payments', p_payments);
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_business_id::text || ':' || p_idempotency_key::text, 0));
  select id, request_payload into purchase_id, old_payload from public.ss_purchases
    where business_id=p_business_id and idempotency_key=p_idempotency_key;
  if purchase_id is not null then
    if old_payload <> payload then raise exception 'Idempotency key was already used for a different purchase' using errcode='22023'; end if;
    return purchase_id;
  end if;
  select is_active into supplier_active from public.ss_suppliers where business_id=p_business_id and id=p_supplier_id for share;
  if supplier_active is distinct from true then raise exception 'Supplier is missing or archived' using errcode='23503'; end if;

  for line in select value from jsonb_array_elements(p_lines) loop
    line_no := line_no + 1;
    if nullif(trim(line->>'item_description'),'') is null or line->>'metal' not in ('gold','silver','other') then
      raise exception 'Item description or metal is invalid' using errcode='22023';
    end if;
    gross_weight := (line->>'gross_weight_g')::numeric;
    net_weight := (line->>'net_weight_g')::numeric;
    unit_cost := (line->>'unit_cost_per_gram')::numeric;
    additional_cost := coalesce((line->>'additional_cost')::numeric,0);
    if gross_weight <= 0 or net_weight <= 0 or net_weight > gross_weight or unit_cost < 0 or additional_cost < 0
       or gross_weight * 10000 <> trunc(gross_weight * 10000)
       or net_weight * 10000 <> trunc(net_weight * 10000)
       or unit_cost * 10000 <> trunc(unit_cost * 10000)
       or additional_cost * 100 <> trunc(additional_cost * 100) then
      raise exception 'Item weights or costs have invalid values or precision' using errcode='22023';
    end if;
    computed_line := round(
      net_weight * unit_cost + additional_cost, 2
    );
    if computed_line <= 0 then raise exception 'Each purchase line total must be greater than zero' using errcode='22023'; end if;
    computed_subtotal := computed_subtotal + computed_line;
  end loop;
  if computed_subtotal <= 0 or computed_subtotal > 999999999999.99 then
    raise exception 'Purchase total is outside the supported range' using errcode='22003';
  end if;

  for payment in select value from jsonb_array_elements(p_payments) loop
    payment_amount := (payment->>'amount')::numeric;
    payment_method := payment->>'method';
    if payment_amount <= 0 or payment_amount * 100 <> trunc(payment_amount * 100)
       or payment_method not in ('cash','upi','bank_transfer','card') then
      raise exception 'Payment amount or method is invalid' using errcode='22023';
    end if;
    computed_paid := computed_paid + payment_amount;
  end loop;
  if computed_paid > computed_subtotal then raise exception 'Payments cannot exceed the purchase total' using errcode='22023'; end if;

  insert into public.ss_purchases (business_id,supplier_id,idempotency_key,request_payload,subtotal,paid_total,created_by)
    values (p_business_id,p_supplier_id,p_idempotency_key,payload,computed_subtotal,computed_paid,actor)
    returning id into purchase_id;

  line_no := 0;
  for line in select value from jsonb_array_elements(p_lines) loop
    line_no := line_no + 1;
    gross_weight := (line->>'gross_weight_g')::numeric;
    net_weight := (line->>'net_weight_g')::numeric;
    unit_cost := (line->>'unit_cost_per_gram')::numeric;
    additional_cost := coalesce((line->>'additional_cost')::numeric,0);
    computed_line := round(
      net_weight * unit_cost + additional_cost, 2
    );
    insert into public.ss_purchase_lines (
      business_id,purchase_id,line_number,item_description,metal,purity,gross_weight_g,net_weight_g,
      unit_cost_per_gram,additional_cost,line_total
    ) values (
      p_business_id,purchase_id,line_no,(line->>'item_description'),(line->>'metal'),nullif(line->>'purity',''),
      gross_weight,net_weight,unit_cost,additional_cost,computed_line
    ) returning id into purchase_line_id;
    insert into public.ss_inventory_movements (business_id,source_type,source_id,source_line_id,metal,purity,weight_delta_g,actor_user_id)
      values (p_business_id,'purchase',purchase_id,purchase_line_id,(line->>'metal'),nullif(line->>'purity',''),net_weight,actor);
  end loop;

  for payment in select value from jsonb_array_elements(p_payments) loop
    insert into public.ss_purchase_payments (business_id,purchase_id,method,amount,reference,received_by)
      values (p_business_id,purchase_id,payment->>'method',(payment->>'amount')::numeric,nullif(payment->>'reference',''),actor)
      returning id into payment_id;
    insert into public.ss_cashbook_entries (business_id,source_type,source_id,direction,amount,method,actor_user_id)
      values (p_business_id,'purchase_payment',payment_id,'out',(payment->>'amount')::numeric,payment->>'method',actor);
  end loop;
  insert into public.ss_audit_events (business_id,actor_user_id,event_type,entity_type,entity_id,safe_metadata)
    values (p_business_id,actor,'purchase.posted','purchase',purchase_id,
      jsonb_build_object('purchase_number',(select purchase_number from public.ss_purchases where id=purchase_id),
        'line_count',jsonb_array_length(p_lines),'payment_count',jsonb_array_length(p_payments),
        'subtotal',computed_subtotal,'paid_total',computed_paid));
  return purchase_id;
end
$function$;

revoke all on function public.ss_post_purchase(uuid,uuid,uuid,jsonb,jsonb) from public, anon, authenticated;
grant execute on function public.ss_post_purchase(uuid,uuid,uuid,jsonb,jsonb) to authenticated;
