-- Atomic supplier purchase posting and owned-stock movement ledger.
-- Customer girvi/custody is intentionally stored elsewhere and never affects this ledger.
-- Apply only after the diagnostic preflight matches the hosted schema.
do $preflight$
begin
  if to_regclass('public.business_profiles') is null
     or to_regclass('public.business_members') is null
     or to_regclass('public.ss_suppliers') is null then
    raise exception 'Required business/supplier tables are missing; inspect hosted schema before applying 006_purchases_inventory';
  end if;
  if to_regprocedure('public.is_business_member(uuid)') is null
     or to_regprocedure('public.has_business_role(uuid,text[])') is null then
    raise exception 'Membership authorization helpers are missing; inspect hosted RLS before applying 006_purchases_inventory';
  end if;
  perform public.is_business_member(null::uuid);
  perform public.has_business_role(null::uuid, array[]::text[]);
end
$preflight$;

create table if not exists public.ss_purchases (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete restrict,
  supplier_id uuid not null,
  purchase_number bigint generated by default as identity,
  idempotency_key uuid not null,
  request_payload jsonb not null,
  subtotal numeric(14,2) not null check (subtotal > 0),
  paid_total numeric(14,2) not null check (paid_total >= 0 and paid_total <= subtotal),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  unique (business_id, id),
  unique (business_id, idempotency_key),
  unique (business_id, purchase_number),
  foreign key (business_id, supplier_id) references public.ss_suppliers(business_id, id) on delete restrict
);

create table if not exists public.ss_purchase_lines (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  purchase_id uuid not null,
  line_number smallint not null check (line_number between 1 and 100),
  item_description text not null check (length(trim(item_description)) between 1 and 180),
  metal text not null check (metal in ('gold','silver','other')),
  purity text,
  gross_weight_g numeric(14,4) not null check (gross_weight_g > 0),
  net_weight_g numeric(14,4) not null check (net_weight_g > 0 and net_weight_g <= gross_weight_g),
  unit_cost_per_gram numeric(14,4) not null check (unit_cost_per_gram >= 0),
  additional_cost numeric(14,2) not null default 0 check (additional_cost >= 0),
  line_total numeric(14,2) not null check (line_total > 0),
  check (purity is null or length(trim(purity)) <= 40),
  created_at timestamptz not null default now(),
  unique (purchase_id, line_number),
  foreign key (business_id, purchase_id) references public.ss_purchases(business_id, id) on delete restrict
);

create table if not exists public.ss_purchase_payments (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  purchase_id uuid not null,
  method text not null check (method in ('cash','upi','bank_transfer','card')),
  amount numeric(14,2) not null check (amount > 0),
  reference text check (reference is null or length(reference) <= 120),
  received_by uuid not null references auth.users(id),
  recorded_at timestamptz not null default now(),
  foreign key (business_id, purchase_id) references public.ss_purchases(business_id, id) on delete restrict
);

create table if not exists public.ss_inventory_movements (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete restrict,
  source_type text not null check (source_type in ('purchase')),
  source_id uuid not null,
  source_line_id uuid not null references public.ss_purchase_lines(id) on delete restrict,
  metal text not null check (metal in ('gold','silver','other')),
  purity text,
  weight_delta_g numeric(14,4) not null check (weight_delta_g > 0),
  actor_user_id uuid not null references auth.users(id),
  recorded_at timestamptz not null default now(),
  unique (source_line_id),
  foreign key (business_id, source_id) references public.ss_purchases(business_id, id) on delete restrict
);

create table if not exists public.ss_cashbook_entries (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete restrict,
  source_type text not null check (source_type in ('purchase_payment')),
  source_id uuid not null references public.ss_purchase_payments(id) on delete restrict,
  direction text not null check (direction in ('in','out')),
  amount numeric(14,2) not null check (amount > 0),
  method text not null check (method in ('cash','upi','bank_transfer','card')),
  actor_user_id uuid not null references auth.users(id),
  recorded_at timestamptz not null default now(),
  unique (source_type, source_id)
);

create table if not exists public.ss_audit_events (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete restrict,
  actor_user_id uuid not null references auth.users(id),
  event_type text not null check (event_type in ('purchase.posted')),
  entity_type text not null check (entity_type in ('purchase')),
  entity_id uuid not null,
  safe_metadata jsonb not null default '{}'::jsonb,
  recorded_at timestamptz not null default now(),
  foreign key (business_id, entity_id) references public.ss_purchases(business_id, id) on delete restrict
);

create index if not exists ss_purchases_business_date_idx on public.ss_purchases (business_id, created_at desc);
create index if not exists ss_purchase_lines_business_idx on public.ss_purchase_lines (business_id, purchase_id);
create index if not exists ss_inventory_business_date_idx on public.ss_inventory_movements (business_id, recorded_at desc);
create index if not exists ss_cashbook_business_date_idx on public.ss_cashbook_entries (business_id, recorded_at desc);

