-- Append-only paid operating expenses. Each posted expense creates its
-- source-linked cashbook outflow in the same transaction.
do $preflight$
begin
  if to_regclass('public.business_profiles') is null
     or to_regclass('public.ss_purchases') is null
     or to_regclass('public.ss_sales') is null
     or to_regclass('public.ss_sale_returns') is null
     or to_regclass('public.ss_inventory_movements') is null
     or to_regclass('public.ss_sale_inventory_movements') is null
     or to_regclass('public.ss_sale_return_inventory_movements') is null
     or to_regclass('public.ss_cashbook_entries') is null
     or to_regclass('public.ss_sale_cashbook_entries') is null
     or to_regclass('public.ss_sale_return_cashbook_entries') is null
     or to_regprocedure('public.has_business_role(uuid,text[])') is null
     or to_regprocedure('public.is_business_member(uuid)') is null
     or to_regprocedure('public.ss_cashbook_page(uuid,timestamptz,timestamptz,integer,integer)') is null then
    raise exception 'Verified sales, purchase, inventory and cashbook ledgers, page RPC, business table and role helpers are required before 014_operating_expenses';
  end if;
  perform public.has_business_role(null::uuid,array[]::text[]);
  perform public.is_business_member(null::uuid);
end
$preflight$;

create table if not exists public.ss_expenses (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete restrict,
  expense_number bigint generated by default as identity,
  idempotency_key uuid not null,
  request_payload jsonb not null,
  category text not null check (length(trim(category)) between 2 and 80),
  description text not null check (length(trim(description)) between 3 and 300),
  payee text check (payee is null or length(trim(payee))<=160),
  amount numeric(14,2) not null check (amount>0),
  method text not null check (method in ('cash','upi','bank_transfer','card')),
  reference text check (reference is null or length(trim(reference))<=120),
  occurred_at timestamptz not null,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  unique (business_id,id),
  unique (business_id,idempotency_key),
  unique (business_id,expense_number)
);

create table if not exists public.ss_expense_cashbook_entries (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete restrict,
  expense_id uuid not null,
  direction text not null default 'out' check (direction='out'),
  amount numeric(14,2) not null check (amount>0),
  method text not null check (method in ('cash','upi','bank_transfer','card')),
  actor_user_id uuid not null references auth.users(id),
  recorded_at timestamptz not null,
  unique (expense_id),
  foreign key (business_id,expense_id) references public.ss_expenses(business_id,id) on delete restrict
);

create table if not exists public.ss_expense_audit_events (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.business_profiles(id) on delete restrict,
  expense_id uuid not null,
  actor_user_id uuid not null references auth.users(id),
  event_type text not null default 'expense.posted' check (event_type='expense.posted'),
  safe_metadata jsonb not null default '{}'::jsonb,
  recorded_at timestamptz not null default now(),
  unique (expense_id),
  foreign key (business_id,expense_id) references public.ss_expenses(business_id,id) on delete restrict
);

create index if not exists ss_expenses_business_date_idx on public.ss_expenses(business_id,occurred_at desc);
create index if not exists ss_expense_cashbook_business_date_idx on public.ss_expense_cashbook_entries(business_id,recorded_at desc);
create index if not exists ss_expense_audit_business_date_idx on public.ss_expense_audit_events(business_id,recorded_at desc);
alter table public.ss_expenses enable row level security;
alter table public.ss_expense_cashbook_entries enable row level security;
alter table public.ss_expense_audit_events enable row level security;
create policy ss_expenses_read_admin on public.ss_expenses for select to authenticated
  using(public.has_business_role(business_id,array['owner','admin']));
create policy ss_expense_cashbook_read_admin on public.ss_expense_cashbook_entries for select to authenticated
  using(public.has_business_role(business_id,array['owner','admin']));
create policy ss_expense_audit_read_admin on public.ss_expense_audit_events for select to authenticated
  using(public.has_business_role(business_id,array['owner','admin']));
revoke all privileges on table public.ss_expenses,public.ss_expense_cashbook_entries,public.ss_expense_audit_events from public,anon,authenticated;
grant select on public.ss_expenses,public.ss_expense_cashbook_entries,public.ss_expense_audit_events to authenticated;

create or replace function public.ss_post_expense(
  p_business_id uuid,p_idempotency_key uuid,p_category text,p_description text,p_payee text,
  p_amount numeric,p_method text,p_reference text,p_occurred_at timestamptz
) returns uuid
language plpgsql security definer set search_path=''
as $function$
declare
  actor uuid := (select auth.uid());
  normalized_category text := trim(coalesce(p_category,''));
  normalized_description text := trim(coalesce(p_description,''));
  normalized_payee text := nullif(trim(coalesce(p_payee,'')),'');
  normalized_reference text := nullif(trim(coalesce(p_reference,'')),'');
  payload jsonb; prior_payload jsonb; expense_id uuid;
begin
  if actor is null then raise exception 'Authentication required' using errcode='42501'; end if;
  if p_business_id is null or not public.has_business_role(p_business_id,array['owner','admin']) then
    raise exception 'Expense posting is restricted to workspace owners and administrators' using errcode='42501';
  end if;
  if p_idempotency_key is null or length(normalized_category) not between 2 and 80
     or length(normalized_description) not between 3 and 300 or length(coalesce(normalized_payee,''))>160
     or p_amount is null or p_amount<=0 or p_amount*100<>trunc(p_amount*100)
     or p_method is null or p_method not in ('cash','upi','bank_transfer','card')
     or length(coalesce(normalized_reference,''))>120 or p_occurred_at is null then
    raise exception 'Expense category, description, amount, method, reference, or date is invalid' using errcode='22023';
  end if;
  payload:=jsonb_build_object('category',normalized_category,'description',normalized_description,'payee',normalized_payee,
    'amount',p_amount,'method',p_method,'reference',normalized_reference,'occurred_at',p_occurred_at);
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_business_id::text||':'||p_idempotency_key::text,0));
  select id,request_payload into expense_id,prior_payload from public.ss_expenses
    where business_id=p_business_id and idempotency_key=p_idempotency_key;
  if expense_id is not null then
    if prior_payload is distinct from payload then raise exception 'Idempotency key was used for different expense details' using errcode='22023'; end if;
    return expense_id;
  end if;
  insert into public.ss_expenses(business_id,idempotency_key,request_payload,category,description,payee,amount,method,reference,occurred_at,created_by)
    values(p_business_id,p_idempotency_key,payload,normalized_category,normalized_description,normalized_payee,p_amount,p_method,normalized_reference,p_occurred_at,actor)
    returning id into expense_id;
  insert into public.ss_expense_cashbook_entries(business_id,expense_id,amount,method,actor_user_id,recorded_at)
    values(p_business_id,expense_id,p_amount,p_method,actor,p_occurred_at);
  insert into public.ss_expense_audit_events(business_id,expense_id,actor_user_id,safe_metadata)
    values(p_business_id,expense_id,actor,jsonb_build_object('amount',p_amount,'category',normalized_category,'method',p_method));
  return expense_id;
end
$function$;
revoke all on function public.ss_post_expense(uuid,uuid,text,text,text,numeric,text,text,timestamptz) from public,anon,authenticated;
grant execute on function public.ss_post_expense(uuid,uuid,text,text,text,numeric,text,text,timestamptz) to authenticated;

-- Extend merged cashbook pagination with admin-only expense outflows. Staff
-- members keep their existing payment visibility and never receive expense rows.
create or replace function public.ss_cashbook_page(
  p_business_id uuid,p_from timestamptz default null,p_through timestamptz default null,p_offset integer default 0,p_limit integer default 200
) returns table(id uuid,payment_id uuid,source text,direction text,amount numeric,method text,recorded_at timestamptz,total_count bigint)
language plpgsql stable security definer set search_path=''
as $function$
begin
  if (select auth.uid()) is null then raise exception 'Authentication required' using errcode='42501'; end if;
  if p_business_id is null or not public.is_business_member(p_business_id) then
    raise exception 'Workspace is missing or cashbook access is not authorized' using errcode='42501';
  end if;
  if p_offset is null or p_offset<0 or p_offset>100000 or p_limit is null or p_limit<1 or p_limit>200 then
    raise exception 'Cashbook page must contain 1 to 200 rows and use a valid offset' using errcode='22023';
  end if;
  if p_from is not null and p_through is not null and p_through<p_from then
    raise exception 'Cashbook end timestamp must not precede its start timestamp' using errcode='22023';
  end if;
  return query
  with entries as (
    select e.id,e.source_id as payment_id,'Purchase payment'::text as source,'out'::text as direction,e.amount,e.method,e.recorded_at
      from public.ss_cashbook_entries e where e.business_id=p_business_id and (p_from is null or e.recorded_at>=p_from) and (p_through is null or e.recorded_at<=p_through)
    union all
    select e.id,e.sale_payment_id,'Sale payment'::text,'in'::text,e.amount,e.method,e.recorded_at from public.ss_sale_cashbook_entries e
      where e.business_id=p_business_id and (p_from is null or e.recorded_at>=p_from) and (p_through is null or e.recorded_at<=p_through)
    union all
    select e.id,e.sale_return_id,'Sale refund'::text,'out'::text,e.amount,e.method,e.recorded_at from public.ss_sale_return_cashbook_entries e
      where e.business_id=p_business_id and (p_from is null or e.recorded_at>=p_from) and (p_through is null or e.recorded_at<=p_through)
    union all
    select e.id,e.expense_id,'Operating expense'::text,'out'::text,e.amount,e.method,e.recorded_at from public.ss_expense_cashbook_entries e
      where e.business_id=p_business_id and public.has_business_role(p_business_id,array['owner','admin'])
        and (p_from is null or e.recorded_at>=p_from) and (p_through is null or e.recorded_at<=p_through)
  )
  select e.id,e.payment_id,e.source,e.direction,e.amount,e.method,e.recorded_at,count(*) over()::bigint
  from entries e order by e.recorded_at desc,e.id desc limit p_limit offset p_offset;
end
$function$;
revoke all on function public.ss_cashbook_page(uuid,timestamptz,timestamptz,integer,integer) from public,anon,authenticated;
grant execute on function public.ss_cashbook_page(uuid,timestamptz,timestamptz,integer,integer) to authenticated;

create or replace function public.ss_business_report_v3(p_business_id uuid,p_from date,p_through date)
returns table(
  report_day date,sales_total numeric,returns_total numeric,purchases_total numeric,expenses_paid numeric,
  cash_received numeric,cash_refunded numeric,cash_paid numeric,
  gold_weight_change_g numeric,silver_weight_change_g numeric,other_weight_change_g numeric,
  sales_count bigint,returns_count bigint,purchases_count bigint,expenses_count bigint
)
language plpgsql stable security definer set search_path=''
as $function$
begin
  if (select auth.uid()) is null then raise exception 'Authentication required' using errcode='42501'; end if;
  if p_business_id is null or not public.has_business_role(p_business_id,array['owner','admin']) then
    raise exception 'Workspace is missing or report access is not authorized' using errcode='42501';
  end if;
  if p_from is null or p_through is null or p_through<p_from or p_through-p_from>365 then
    raise exception 'Report range must be between one and 366 days' using errcode='22023';
  end if;
  return query
  with days as (select g.day_ts::date day from generate_series(p_from::timestamp,p_through::timestamp,interval '1 day') g(day_ts)),
  sales as (
    select (s.created_at at time zone 'Asia/Kolkata')::date day,sum(s.subtotal)::numeric total,count(*)::bigint n from public.ss_sales s
    where s.business_id=p_business_id and s.created_at >= (p_from::timestamp at time zone 'Asia/Kolkata') and s.created_at < ((p_through+1)::timestamp at time zone 'Asia/Kolkata') group by 1
  ), sale_returns as (
    select (r.recorded_at at time zone 'Asia/Kolkata')::date day,sum(r.original_line_amount)::numeric total,count(*)::bigint n from public.ss_sale_returns r
    where r.business_id=p_business_id and r.recorded_at >= (p_from::timestamp at time zone 'Asia/Kolkata') and r.recorded_at < ((p_through+1)::timestamp at time zone 'Asia/Kolkata') group by 1
  ), purchases as (
    select (p.created_at at time zone 'Asia/Kolkata')::date day,sum(p.subtotal)::numeric total,count(*)::bigint n from public.ss_purchases p
    where p.business_id=p_business_id and p.created_at >= (p_from::timestamp at time zone 'Asia/Kolkata') and p.created_at < ((p_through+1)::timestamp at time zone 'Asia/Kolkata') group by 1
  ), expenses as (
    select (x.occurred_at at time zone 'Asia/Kolkata')::date day,sum(x.amount)::numeric total,count(*)::bigint n from public.ss_expenses x
    where x.business_id=p_business_id and x.occurred_at >= (p_from::timestamp at time zone 'Asia/Kolkata') and x.occurred_at < ((p_through+1)::timestamp at time zone 'Asia/Kolkata') group by 1
  ), sale_cash as (
    select (e.recorded_at at time zone 'Asia/Kolkata')::date day,sum(e.amount)::numeric total from public.ss_sale_cashbook_entries e
    where e.business_id=p_business_id and e.recorded_at >= (p_from::timestamp at time zone 'Asia/Kolkata') and e.recorded_at < ((p_through+1)::timestamp at time zone 'Asia/Kolkata') group by 1
  ), refund_cash as (
    select (e.recorded_at at time zone 'Asia/Kolkata')::date day,sum(e.amount)::numeric total from public.ss_sale_return_cashbook_entries e
    where e.business_id=p_business_id and e.recorded_at >= (p_from::timestamp at time zone 'Asia/Kolkata') and e.recorded_at < ((p_through+1)::timestamp at time zone 'Asia/Kolkata') group by 1
  ), purchase_cash as (
    select (e.recorded_at at time zone 'Asia/Kolkata')::date day,sum(e.amount)::numeric total from public.ss_cashbook_entries e
    where e.business_id=p_business_id and e.direction='out' and e.recorded_at >= (p_from::timestamp at time zone 'Asia/Kolkata') and e.recorded_at < ((p_through+1)::timestamp at time zone 'Asia/Kolkata') group by 1
  ), stock as (
    select (m.recorded_at at time zone 'Asia/Kolkata')::date day,m.metal,sum(m.weight_delta_g)::numeric change from (
      select business_id,recorded_at,metal,weight_delta_g from public.ss_inventory_movements
      union all select business_id,recorded_at,metal,weight_delta_g from public.ss_sale_inventory_movements
      union all select business_id,recorded_at,metal,weight_delta_g from public.ss_sale_return_inventory_movements
    ) m where m.business_id=p_business_id and m.recorded_at >= (p_from::timestamp at time zone 'Asia/Kolkata') and m.recorded_at < ((p_through+1)::timestamp at time zone 'Asia/Kolkata') group by 1,2
  )
  select d.day,coalesce(s.total,0),coalesce(sr.total,0),coalesce(p.total,0),coalesce(x.total,0),coalesce(sc.total,0),coalesce(rc.total,0),coalesce(pc.total,0),
    coalesce(max(st.change) filter(where st.metal='gold'),0),coalesce(max(st.change) filter(where st.metal='silver'),0),coalesce(max(st.change) filter(where st.metal='other'),0),
    coalesce(s.n,0),coalesce(sr.n,0),coalesce(p.n,0),coalesce(x.n,0)
  from days d left join sales s on s.day=d.day left join sale_returns sr on sr.day=d.day left join purchases p on p.day=d.day left join expenses x on x.day=d.day
    left join sale_cash sc on sc.day=d.day left join refund_cash rc on rc.day=d.day left join purchase_cash pc on pc.day=d.day left join stock st on st.day=d.day
  group by d.day,s.total,sr.total,p.total,x.total,sc.total,rc.total,pc.total,s.n,sr.n,p.n,x.n order by d.day desc;
end
$function$;
revoke all on function public.ss_business_report_v3(uuid,date,date) from public,anon,authenticated;
grant execute on function public.ss_business_report_v3(uuid,date,date) to authenticated;
